"""Сценарий доклада: по слайду 2–4 фразы, числа из F. Тот же текст кладётся в заметки докладчика."""
from __future__ import annotations

import re

from .facts import DATE_LABEL, DATES, NBSP, fmt, plural

WPM = 125  # слов в минуту: спокойная речь на показе


def _n(x, d=0, sign=False):
    return fmt(x, d, sign).replace(NBSP, " ")


def _rub(x) -> str:
    return f"{_n(x)} {plural(round(x), 'рубль', 'рубля', 'рублей')}"


def build(F: dict, cfg: dict) -> list[dict]:
    L, Fin, o = F["ladder"], F["final"], F.get("opt")
    Sh = F.get("shap")
    cfgn = F["cfg"]
    sl: list[dict] = []

    def add(title, text):
        sl.append({"title": title, "text": " ".join(text.split())})

    add("Титул", f"""Здравствуйте! Меня зовут {cfg['author']}, это проект «Агрокаст» — решение задачи 5 кейса «Своё Фермерство».
Мы прогнозируем урожайность на пять дат сезона, с 1 мая до конца, и на этой основе подсказываем, как немного изменить посевы, чтобы заработать больше.
За шесть минут я покажу не просто обученную модель, а полноценное исследование: данные, честную проверку, результаты и работающий сайт.""")

    add("Задача кейса", """Кейс просит калькулятор урожайности в тоннах на гектар и в общем объёме и объяснение пользы для планирования затрат и доходов.
Фермеру прогноз нужен, чтобы решать, что сеять и сколько вложить, банку — чтобы видеть риск кредитов до уборки.
Мы пошли дальше: прогноз превращается в рекомендацию, что именно поменять в плане посевов.""")

    add("Масштаб работы", f"""Это исследование на большом массиве данных: {F['n_sources']} источников — статистика ЕМИСС, погода, спутники, почвы — и {_n(F['raw_gb'], 1)} гигабайта сырых данных, {_n(F['rows_mln'])} {plural(round(F['rows_mln']), 'миллион', 'миллиона', 'миллионов')} строк наблюдений.
В таблице модели {_n(F['model_cols'])} {plural(F['model_cols'], 'столбец', 'столбца', 'столбцов')} признаков, а на единой проверке сравнено {_n(cfgn['total'])} {plural(cfgn['total'], 'конфигурация', 'конфигурации', 'конфигураций')} моделей, включая {_n(cfgn['optuna_trials'] / 1e3, 1)} тысячи попыток подбора гиперпараметров.
Всё это держится на {F['n_tests']} автоматических тестах.""")

    add("Конвейер данных", """Данные идут строго слева направо: сырые файлы, разбор, исследовательский слой и чистый слой, из которого питаются модель и сайт.
При чистке строки не удаляются, а помечаются флагами, а любой слой пересобирается скриптом.
Поэтому результат воспроизводим, и каждый шаг можно проверить.""")

    add("Методика", """Модель устроена просто: урожайность — это тренд, умноженный на поправку за погоду, спутник и почву.
Прогноз строится на пять дат, и всё, что наступит позже даты прогноза, замаскировано.
Проверка скользящая, по времени: для каждого года с 2012 по 2025 модель обучается только на прошлом. Случайного разбиения нет, потому что год — общий шок для всех регионов.""")

    m = L["mape"]
    add("Лесенка моделей", f"""Главный результат — лесенка моделей. Прогноз «как в прошлом году» ошибается в среднем на {_n(m[0])} процентов, один тренд — на {_n(m[1], 1)}, линейная модель с погодой — на {_n(m[2])}, а перебор с ансамблем — на {_n(m[4], 1)}.
Средняя ошибка MAE ниже на {_n(L['gain_end'])} процентов.
Скажу честно: бустинг «из коробки» со спутником линейную модель не обгоняет, весь выигрыш даёт настройка и ансамбль.""")

    add("Качество по датам и культурам", f"""Прогноз уточняется по ходу сезона: уже 1 мая ошибка на {_n(L['by_date']['all'][0])} процентов ниже, чем у «прошлого года», а к концу сезона — на {_n(L['gain_end'])}.
Отложенные годы 2019–2025, которые не участвовали в подборе, дают тот же результат, поэтому это не подгонка.
Озимая пшеница предсказуема уже с 1 мая, остальным культурам нужны июль и август. Восьмидесятипроцентный интервал накрывает факт в {_n(100 * Fin['cov_min'])}–{_n(100 * Fin['cov_max'])} процентах случаев, его полуширина — около {_n(Fin['halfwidth_end'])} процентов.""")

    if Sh:
        add("Что двигает урожайность", f"""Модель объяснима. По SHAP погода даёт от {_n(Sh['weather_rng'][0])} до {_n(Sh['weather_rng'][1])} процентов вклада, спутник MODIS — от {_n(Sh['sat_rng'][0])} до {_n(Sh['sat_rng'][1])}, больше всего у сои и подсолнечника.
Главные признаки агрономически осмысленны: у озимой пшеницы это выход из зимы и перегрев в мае–июне, у кукурузы — засуха в июле, у свёклы — водный баланс.""")
    else:
        add("Что двигает урожайность", "Блок SHAP ждёт данных.")

    if o:
        d5, bt = o["d5"], o["bt"]["d5"]
        med = (f" По субъектам медиана — {_rub(d5['median_ha'])} на гектар, выигрыш есть у {_n(d5['share_up'])} процентов регионов."
               if "median_ha" in d5 else "")
        add("Оптимизация посевов", f"""Вторая часть — оптимизация структуры посевов: сценарная стохастическая оптимизация с критерием CVaR, который учитывает плохие годы, и ограничением на отклонение от текущего плана.
Если менять долю каждой культуры не больше чем на 5 процентных пунктов, ожидаемая прибыль растёт в среднем на {_rub(d5['gain_ha'])} на гектар и почти столько же, {_n(d5['cvar_gain_ha'])}, — в худшие 20 процентов сезонов.{med}
Проверка на прошлом, с 2012 по 2025 год, на исторических сценариях и только по данным до каждого года: фактический выигрыш {_rub(bt['real'])} на гектар, это {_n(bt['realization'])} процентов обещанного, и план лучше текущего в {_n(bt['win'])} процентах случаев. Затраты — наши допущения, поэтому эффект читаем как верхнюю оценку.""")
    else:
        add("Оптимизация посевов", "Блок оптимизации ждёт данных.")

    add("Сайт", """Всё это собрано в сайте «Агрокаст»: карта по регионам и культурам со шкалой дат, карточка региона с факторами прогноза, калькулятор хозяйства с поправками на почву, сорт и агротехнику и экран оптимизации с ползунком «менять не больше X процентов».
Сайт статический, работает без сервера, а код, данные и отчёт лежат в репозитории.""")

    add("Ограничения и развитие", f"""Ограничения называю прямо: уровень прогноза — регион, ряды короткие, интервалы широкие, а затраты в оптимизации — допущения.
Дальше — районы и хозяйства, спутник в реальном времени, совместные сценарии цены и урожая, удобрения и агротехника и интеграция с данными банка.""")

    gain = f"{_rub(o['d5']['gain_ha'])} на гектар" if o else "заметный эффект"
    add("Итоги", f"""Итог: ошибка прогноза снижена на {_n(L['gain_end'])} процентов на честной проверке по времени, собрана воспроизводимая цепочка из {F['n_sources']} источников и {_n(F['model_cols'])} признаков, а оптимизация даёт {gain} от малых изменений плана.
Спасибо за внимание, готов ответить на вопросы.""")
    return sl


def words(text: str) -> int:
    return len(re.findall(r"\w+", text))


def qa(F: dict) -> list[tuple[str, str]]:
    L, Fin, o = F["ladder"], F["final"], F.get("opt")
    out = [
        ("Почему бустинг со спутником не лучше линейной модели?",
         f"Ступень 3 — модель по умолчанию, без настройки: {fmt(L['gain'][3], 1)} % против {fmt(L['gain'][2], 1)} % у Ridge. Спутник даёт вклад у сои и подсолнечника, "
         f"а у зерновых повторяет сигнал погоды. Выигрыш {fmt(L['gain'][4])} % даёт перебор конфигураций и ансамбль, поэтому показываем обе ступени."),
        ("Как исключена утечка будущего?",
         "Тренды и нормы погоды считаются только по годам < t; для прогноза на дату месяцы после неё маскируются; гиперпараметры подобраны по 2012–2018, годы 2019–2025 отложены; случайного разбиения нет."),
        ("Откуда взяты затраты в оптимизации?",
         "Это допущения по отраслевым обзорам; масштаб сверен с производственной себестоимостью Росстата (ЕМИСС 42381)"
         + (f": {fmt(o['cost_rosstat_2025'] / 1e3, 1)} тыс. ₽/га в 2025 г." if o and "cost_rosstat_2025" in o else "")
         + ", соотношение между культурами не проверялось. Поэтому эффект — верхняя оценка; на сайте затраты меняются под хозяйство."),
        ("Почему интервалы такие широкие?",
         f"Это честная неопределённость: конформный 80 %-й интервал по ошибкам прошлых лет, полуширина ±{fmt(Fin['halfwidth_end'])} % в конце сезона; он накрывает факт в {fmt(100 * Fin['cov_min'])}–{fmt(100 * Fin['cov_max'])} % случаев. Точечный прогноз без интервала мы не показываем."),
        ("Что с 2025 годом?",
         "Итогов Росстата по полевым культурам нет, урожайность восстановлена как «сбор / посевная»; все ступени лесенки ошибаются относительно одной и той же «правды»."),
    ]
    if o:
        if "median_ha" in o["d5"]:
            out.append(("Не держится ли средний эффект на нескольких крупных регионах?",
                        f"Среднее взвешено по площади: +{fmt(o['d5']['gain_ha'])} ₽/га. По субъектам медиана — +{fmt(o['d5']['median_ha'])} ₽/га, "
                        f"верхний квартиль +{fmt(o['d5']['q75_ha'])} ₽/га, выигрыш есть у {fmt(o['d5']['share_up'])} % субъектов; "
                        "у хозяйства, чей план уже на пределе норм севооборота, эффект скромный — и калькулятор честно говорит «план близок к лучшему»."))
        if "krasnodar_d10_pct" in o:
            out.append(("Почему на сайте для Краснодарского края эффект всего около процента?",
                        f"Для края в целом при δ = 10 п.п. прирост ожидаемой прибыли +{fmt(o['krasnodar_d10_pct'], 1)} %, а у типового хозяйства с планом "
                        "озимая пшеница 60 % + подсолнечник 15 % самые маржинальные культуры уже на пределе норм: переносить почти некуда. Это вывод, а не ошибка расчёта."))
        out.append(("Почему CVaR не улучшил результат на истории?",
                    f"По {o['n_scen']} сценариям хвост худших 20 % — это всего около {round(0.2 * o['n_scen'])} точек, оценка шумная, а выгодные культуры чаще и менее рискованны. Оставляем λ = 0,5 как разумный компромисс, а не как доказанно лучший выбор."))
    return out


def render(F: dict, cfg: dict, slides: list[dict]) -> str:
    total_words = sum(words(s["text"]) for s in slides)
    mins = total_words / WPM
    lines = ["# Сценарий доклада", "",
             f"*Сгенерировано `src/deck/build_deck.py` {F['built']}; числа берутся из таблиц проекта, правки текста — в `src/deck/script.py`. "
             f"Объём: {total_words} слов, около {mins:.1f} мин при {WPM} словах в минуту.*", ""]
    for i, s in enumerate(slides, 1):
        sec = words(s["text"]) / WPM * 60
        lines += [f"## {i}. {s['title']} (≈{sec:.0f} с)", "", s["text"], ""]
    lines += ["## Возможные вопросы жюри", ""]
    for q, a in qa(F):
        lines += [f"**{q}** {a}", ""]
    lines += ["## Контроль свежести источников", "", "| источник | изменён |", "|---|---|"]
    for k, v in sorted(F["stamps"].items()):
        lines.append(f"| `{k}` | {v} |")
    lines.append("")
    if "opt" in F:
        o = F["opt"]
        lines += [f"Оптимизация: сценарии — `{o['scenario_source']}`, выгрузка {o['generated']}; "
                  f"{'расчёт новее итоговых прогнозов' if o['fresh'] else '**расчёт старше итоговых прогнозов или не на итоговой модели — перезапустить `src/optimize/run.py all`**'}. "
                  f"Текст `reports/optimization.md` изменён {o['md_stamp']} (слайды берут числа из таблиц, а не из текста).", ""]
    if F["missing"]:
        lines += ["**Не хватает данных:**", ""] + [f"- {m}" for m in F["missing"]] + [""]
    return "\n".join(lines)
